def square(x, y):
    "Draw square using path at (x, y)."
    path.up()
    path.goto(x, y)
    path.down()
    path.begin_fill()

    for count in range(4):
        path.forward(20)
        path.left(90)

    path.end_fill()

def offset(point):
    "Return offset of point in tiles."
    x = (floor(point.x, 20) + 200) / 20
    y = (180 - floor(point.y, 20)) / 20
    index = int(x + y * 20)
    return index

def valid(point):
    "Return True if point is valid in tiles."
    index = offset(point)

    if tiles[index] == 0:
        return False

    index = offset(point + 19)

    if tiles[index] == 0:
        return False

    return point.x % 20 == 0 or point.y % 20 == 0

def world():
    "Draw world using path."
    bgcolor('black')
    path.color('blue')

    for index in range(len(tiles)):
        tile = tiles[index]

        if tile > 0:
            x = (index % 20) * 20 - 200
            y = 180 - (index // 20) * 20
            square(x, y)

            if tile == 1:
                path.up()
                path.goto(x + 10, y + 10)
                path.dot(2, 'white')

def move():
    "Move pacman and all ghosts."
    writer.undo()
    writer.write(state['score'])

    clear()

    if valid(pacman + aim):
        pacman.move(aim)

    index = offset(pacman)

    if tiles[index] == 1:
        tiles[index] = 2
        state['score'] += 1
        x = (index % 20) * 20 - 200
        y = 180 - (index // 20) * 20
        square(x, y)

    up()
    goto(pacman.x + 10, pacman.y + 10)
    dot(20, 'yellow')

    for point, course, color_name in ghosts:
        
        if color_name == 'red':
            target = vector(pacman.x, pacman.y)
        elif color_name == 'pink':
            
            target = vector(pacman.x + aim.x * 10, pacman.y + aim.y * 10)
        elif color_name == 'cyan':
            
            target = vector(pacman.x - aim.x * 6, pacman.y - aim.y * 6)
        elif color_name == 'orange':
            
            if abs(pacman - point) < 100:
                target = vector(100, -160)
            else:
                target = vector(pacman.x, pacman.y)

        options = [vector(5, 0), vector(-5, 0), vector(0, 5), vector(0, -5)]
        backward = vector(-course.x, -course.y)
        
        
        valid_options = []
        for opt in options:
            if valid(point + opt):
                valid_options.append(opt)
                
        
        forward_options = []
        for opt in valid_options:
            if opt != backward:
                forward_options.append(opt)
                
        choices = forward_options if len(forward_options) > 0 else valid_options

        
        best_plan = course
        min_dist = float('inf')
        for opt in choices:
            dist = abs((point + opt) - target)
            if dist < min_dist:
                min_dist = dist
                best_plan = opt

        
        if (point.x % 20 == 0 and point.y % 20 == 0) or not valid(point + course):
            course.x = best_plan.x
            course.y = best_plan.y

        point.move(course)

        up()
        goto(point.x + 10, point.y + 10)
        dot(20, color_name)

    update()

    for point, course, color_name in ghosts:
        if abs(pacman - point) < 20:
            return

    ontimer(move, 100)

def change(x, y):
    "Change pacman aim if valid."
    if valid(pacman + vector(x, y)):
        aim.x = x
        aim.y = y

